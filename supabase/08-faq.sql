revoke all on function public.faq_save(bigint, text, text, text, jsonb, jsonb, text, integer),
                       public.faq_set_hidden(bigint, boolean, text), public.faq_move(bigint, integer, text),
                       public.faq_move_category(text, integer, text), public.faq_restore_version(bigint, text),
                       public.faq_delete(bigint, text), public.faq_undelete(bigint, text),
                       public.faq_as_of(timestamptz) from public, anon;
grant execute on function public.faq_save(bigint, text, text, text, jsonb, jsonb, text, integer),
                          public.faq_set_hidden(bigint, boolean, text), public.faq_move(bigint, integer, text),
                          public.faq_move_category(text, integer, text), public.faq_restore_version(bigint, text),
                          public.faq_delete(bigint, text), public.faq_undelete(bigint, text),
                          public.faq_as_of(timestamptz) to authenticated;

