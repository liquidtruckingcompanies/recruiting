-- Liquid Trucking Operations Center: Driver FAQ (Recruiting).
-- Run once in Supabase after 07-feedback-delete.sql: SQL Editor -> New query -> paste all of this -> Run. Safe to run again.
-- Then run 09-faq-load.sql once to load the starting FAQs.
--
-- Who can do what:
--   Read FAQs + full history: any active signed-in user who can view the "Driver FAQ" page (set in Admin).
--   Add / edit / hide / reorder / restore old versions: users with Edit access to the page (admins always).
--   Delete (moves to a Deleted list, restorable): the site owner only.
-- Every change needs a reason and is written to faq_versions with who, when, and the full before + after.
-- The page can only change FAQs through the functions below, so history can't be skipped or edited.

-- 1. The page, so it shows up in Admin with view/edit access like the Hiring Map.
insert into public.site_pages (id, name, public_view, sort) values ('faq', 'Driver FAQ', true, 20)
on conflict (id) do nothing;

-- 2. Access helpers.
create or replace function public.faq_can_read()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.editors where email = lower(auth.jwt() ->> 'email') and active)
     and public.can_view('faq');
$$;
create or replace function public.faq_can_edit()
returns boolean language sql stable security definer set search_path = public as $$
  select public.page_access('faq') = 'edit';
$$;
grant execute on function public.faq_can_read(), public.faq_can_edit() to authenticated;

-- 3. Tables.
create table if not exists public.faq_categories (
  name text primary key,
  sort integer not null default 0
);

create table if not exists public.faq (
  id              bigint generated by default as identity primary key,
  category        text not null,
  question        text not null,
  answer          text not null default '',
  links           jsonb not null default '[]'::jsonb,   -- [{label, url}]
  media           jsonb not null default '[]'::jsonb,   -- [{path, name, type, size}] in the private "faq" storage bucket
  sort            integer not null default 0,
  hidden          boolean not null default false,
  version         integer not null default 1,
  created_at      timestamptz not null default now(),
  created_by_name text,
  updated_at      timestamptz not null default now(),
  updated_by_name text,
  deleted_at      timestamptz,
  deleted_by_name text
);

create table if not exists public.faq_versions (
  id       bigint generated always as identity primary key,
  faq_id   bigint references public.faq(id),          -- null = category order change
  version  integer,
  action   text not null check (action in ('imported','created','edited','moved','hidden','unhidden','restored','deleted','undeleted','categories')),
  reason   text not null,
  before   jsonb,
  after    jsonb,
  by_email text,
  by_name  text,
  at       timestamptz not null default now()
);
create index if not exists faq_versions_faq_at on public.faq_versions (faq_id, at);

alter table public.faq_categories enable row level security;
alter table public.faq            enable row level security;
alter table public.faq_versions   enable row level security;

drop policy if exists "faq categories read" on public.faq_categories;
create policy "faq categories read" on public.faq_categories for select to authenticated using (public.faq_can_read());

-- Hidden FAQs: editors only. Deleted FAQs: owner only.
drop policy if exists "faq read" on public.faq;
create policy "faq read" on public.faq for select to authenticated using (
  public.faq_can_read() and (
    (deleted_at is null and (not hidden or public.faq_can_edit()))
    or (deleted_at is not null and public.is_owner())
  ));

-- History follows the FAQ it belongs to (the faq policy above applies inside this check).
drop policy if exists "faq history read" on public.faq_versions;
create policy "faq history read" on public.faq_versions for select to authenticated using (
  public.faq_can_read() and (faq_id is null or exists (select 1 from public.faq f where f.id = faq_id)));

-- 4. Internal helpers (not callable from the site).
create or replace function public.faq_snap(f public.faq)
returns jsonb language sql immutable as $$
  select jsonb_build_object('category', f.category, 'question', f.question, 'answer', f.answer,
    'links', f.links, 'media', f.media, 'sort', f.sort, 'hidden', f.hidden, 'deleted', f.deleted_at is not null);
$$;

create or replace function public.faq_reason(p text)
returns text language plpgsql immutable as $$
declare r text := btrim(coalesce(p, ''));
begin
  if r = '' then raise exception 'Add a short reason for this change.' using errcode = '22023'; end if;
  return left(r, 1000);
end $$;

-- Links: up to 50, each {label, url}; only http:// or https:// web addresses.
create or replace function public.faq_clean_links(p jsonb)
returns jsonb language plpgsql immutable as $$
declare e jsonb; u text; l text; out jsonb := '[]'::jsonb;
begin
  if p is null or jsonb_typeof(p) <> 'array' then return '[]'::jsonb; end if;
  if jsonb_array_length(p) > 50 then raise exception 'Too many links (50 max).' using errcode = '22023'; end if;
  for e in select * from jsonb_array_elements(p) loop
    u := btrim(coalesce(e ->> 'url', ''));
    l := btrim(coalesce(e ->> 'label', ''));
    if u = '' and l = '' then continue; end if;
    if u !~* '^https?://[^\s<>"]+$' or length(u) > 2000 then
      raise exception 'This link is not a valid web address: %', left(u, 200) using errcode = '22023';
    end if;
    out := out || jsonb_build_array(jsonb_build_object('label', left(case when l = '' then u else l end, 200), 'url', u));
  end loop;
  return out;
end $$;

-- Media: up to 30 files, each {path, name, type, size}, stored in the private "faq" bucket.
create or replace function public.faq_clean_media(p jsonb)
returns jsonb language plpgsql immutable as $$
declare e jsonb; out jsonb := '[]'::jsonb;
begin
  if p is null or jsonb_typeof(p) <> 'array' then return '[]'::jsonb; end if;
  if jsonb_array_length(p) > 30 then raise exception 'Too many files (30 max).' using errcode = '22023'; end if;
  for e in select * from jsonb_array_elements(p) loop
    if coalesce(e ->> 'path', '') = '' or (e ->> 'path') like '%..%' then
      raise exception 'Bad file reference.' using errcode = '22023';
    end if;
    out := out || jsonb_build_array(jsonb_build_object(
      'path', left(e ->> 'path', 500), 'name', left(coalesce(nullif(e ->> 'name', ''), 'file'), 200),
      'type', left(coalesce(e ->> 'type', ''), 100), 'size', coalesce((e ->> 'size')::bigint, 0)));
  end loop;
  return out;
end $$;

create or replace function public.faq_me()
returns table (email text, name text) language sql stable security definer set search_path = public as $$
  select e.email, e.name from public.editors e where e.email = lower(auth.jwt() ->> 'email');
$$;

-- 5. Actions the page can call.

-- Create (p_id null) or edit an FAQ. p_version = the version the editor started from; if someone else saved
-- in the meantime, the save is refused instead of quietly overwriting their change.
create or replace function public.faq_save(p_id bigint, p_category text, p_question text, p_answer text,
                                           p_links jsonb, p_media jsonb, p_reason text, p_version integer)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  me record; f public.faq; old public.faq; r text := public.faq_reason(p_reason);
  c text := left(btrim(coalesce(p_category, '')), 80);
  q text := left(btrim(coalesce(p_question, '')), 500);
  a text := left(coalesce(p_answer, ''), 20000);
  l jsonb := public.faq_clean_links(p_links);
  m jsonb := public.faq_clean_media(p_media);
begin
  if not public.faq_can_edit() then raise exception 'You don''t have edit access to the Driver FAQ.' using errcode = '42501'; end if;
  if c = '' then raise exception 'Pick a category.' using errcode = '22023'; end if;
  if length(q) < 3 then raise exception 'Write the question.' using errcode = '22023'; end if;
  select * into me from public.faq_me();
  insert into public.faq_categories (name, sort)
    select c, coalesce((select max(sort) from public.faq_categories), 0) + 10
    where not exists (select 1 from public.faq_categories where name = c);

  if p_id is null then
    insert into public.faq (category, question, answer, links, media, sort, created_by_name, updated_by_name)
    values (c, q, a, l, m, coalesce((select max(sort) from public.faq where category = c), 0) + 10, me.name, me.name)
    returning * into f;
    insert into public.faq_versions (faq_id, version, action, reason, before, after, by_email, by_name)
    values (f.id, f.version, 'created', r, null, public.faq_snap(f), me.email, me.name);
    return jsonb_build_object('id', f.id, 'version', f.version);
  end if;

  select * into old from public.faq where id = p_id for update;
  if not found or old.deleted_at is not null then raise exception 'That FAQ no longer exists.' using errcode = 'P0002'; end if;
  if p_version is not null and old.version <> p_version then
    raise exception 'Someone else saved this FAQ while you were editing. Reload it to see their version, then make your change again.' using errcode = '40001';
  end if;
  if old.category = c and old.question = q and old.answer = a and old.links = l and old.media = m then
    raise exception 'Nothing changed.' using errcode = '22023';
  end if;
  update public.faq set category = c, question = q, answer = a, links = l, media = m,
    sort = case when old.category = c then old.sort else coalesce((select max(sort) from public.faq where category = c), 0) + 10 end,
    version = old.version + 1, updated_at = now(), updated_by_name = me.name
  where id = p_id returning * into f;
  insert into public.faq_versions (faq_id, version, action, reason, before, after, by_email, by_name)
  values (f.id, f.version, 'edited', r, public.faq_snap(old), public.faq_snap(f), me.email, me.name);
  return jsonb_build_object('id', f.id, 'version', f.version);
end $$;

-- Hide (take off the page, editors still see it) or unhide.
create or replace function public.faq_set_hidden(p_id bigint, p_hidden boolean, p_reason text)
returns integer language plpgsql security definer set search_path = public as $$
declare me record; f public.faq; old public.faq; r text := public.faq_reason(p_reason);
begin
  if not public.faq_can_edit() then raise exception 'You don''t have edit access to the Driver FAQ.' using errcode = '42501'; end if;
  select * into me from public.faq_me();
  select * into old from public.faq where id = p_id and deleted_at is null for update;
  if not found then raise exception 'That FAQ no longer exists.' using errcode = 'P0002'; end if;
  if old.hidden = p_hidden then return old.version; end if;
  update public.faq set hidden = p_hidden, version = old.version + 1, updated_at = now(), updated_by_name = me.name
  where id = p_id returning * into f;
  insert into public.faq_versions (faq_id, version, action, reason, before, after, by_email, by_name)
  values (f.id, f.version, case when p_hidden then 'hidden' else 'unhidden' end, r, public.faq_snap(old), public.faq_snap(f), me.email, me.name);
  return f.version;
end $$;

-- Move an FAQ up (-1) or down (+1) within its category.
create or replace function public.faq_move(p_id bigint, p_dir integer, p_reason text)
returns void language plpgsql security definer set search_path = public as $$
declare me record; f public.faq; old public.faq; nb public.faq; r text := public.faq_reason(p_reason);
begin
  if not public.faq_can_edit() then raise exception 'You don''t have edit access to the Driver FAQ.' using errcode = '42501'; end if;
  select * into me from public.faq_me();
  select * into old from public.faq where id = p_id and deleted_at is null for update;
  if not found then raise exception 'That FAQ no longer exists.' using errcode = 'P0002'; end if;
  if p_dir < 0 then
    select * into nb from public.faq where category = old.category and deleted_at is null and (sort, id) < (old.sort, old.id)
      order by sort desc, id desc limit 1 for update;
  else
    select * into nb from public.faq where category = old.category and deleted_at is null and (sort, id) > (old.sort, old.id)
      order by sort, id limit 1 for update;
  end if;
  if nb.id is null then raise exception 'It''s already at the % of its category.', case when p_dir < 0 then 'top' else 'bottom' end using errcode = '22023'; end if;
  -- Give every FAQ in the category its own position first, so a swap always changes the order.
  update public.faq x set sort = s.n * 10
    from (select id, row_number() over (order by sort, id) n from public.faq where category = old.category and deleted_at is null) s
    where x.id = s.id;
  select * into old from public.faq where id = p_id;
  select * into nb from public.faq where id = nb.id;
  update public.faq set sort = old.sort where id = nb.id;
  update public.faq set sort = nb.sort, version = old.version + 1, updated_at = now(), updated_by_name = me.name
  where id = p_id returning * into f;
  insert into public.faq_versions (faq_id, version, action, reason, before, after, by_email, by_name)
  values (f.id, f.version, 'moved', r, public.faq_snap(old) || jsonb_build_object('dir', p_dir), public.faq_snap(f) || jsonb_build_object('dir', p_dir), me.email, me.name);
end $$;

-- Move a whole category up (-1) or down (+1).
create or replace function public.faq_move_category(p_name text, p_dir integer, p_reason text)
returns void language plpgsql security definer set search_path = public as $$
declare me record; r text := public.faq_reason(p_reason); b jsonb; a jsonb; cur record; nb record;
begin
  if not public.faq_can_edit() then raise exception 'You don''t have edit access to the Driver FAQ.' using errcode = '42501'; end if;
  select * into me from public.faq_me();
  perform 1 from public.faq_categories for update;
  update public.faq_categories x set sort = s.n * 10
    from (select name, row_number() over (order by sort, name) n from public.faq_categories) s where x.name = s.name;
  select coalesce(jsonb_agg(name order by sort), '[]'::jsonb) into b from public.faq_categories;
  select * into cur from public.faq_categories where name = p_name;
  if cur.name is null then raise exception 'Unknown category.' using errcode = 'P0002'; end if;
  if p_dir < 0 then select * into nb from public.faq_categories where sort < cur.sort order by sort desc limit 1;
  else select * into nb from public.faq_categories where sort > cur.sort order by sort limit 1; end if;
  if nb.name is null then raise exception 'It''s already at the % of the list.', case when p_dir < 0 then 'top' else 'bottom' end using errcode = '22023'; end if;
  update public.faq_categories set sort = nb.sort where name = cur.name;
  update public.faq_categories set sort = cur.sort where name = nb.name;
  select coalesce(jsonb_agg(name order by sort), '[]'::jsonb) into a from public.faq_categories;
  insert into public.faq_versions (faq_id, version, action, reason, before, after, by_email, by_name)
  values (null, null, 'categories', r, jsonb_build_object('order', b, 'moved', p_name), jsonb_build_object('order', a, 'moved', p_name), me.email, me.name);
end $$;

-- Bring back the text, links and files from an older version (recorded as a new change).
create or replace function public.faq_restore_version(p_version_id bigint, p_reason text)
returns integer language plpgsql security definer set search_path = public as $$
declare me record; v public.faq_versions; f public.faq; old public.faq; r text := public.faq_reason(p_reason); s jsonb;
begin
  if not public.faq_can_edit() then raise exception 'You don''t have edit access to the Driver FAQ.' using errcode = '42501'; end if;
  select * into me from public.faq_me();
  select * into v from public.faq_versions where id = p_version_id;
  if v.id is null or v.faq_id is null or v.after is null then raise exception 'That version can''t be restored.' using errcode = 'P0002'; end if;
  s := v.after;
  select * into old from public.faq where id = v.faq_id and deleted_at is null for update;
  if not found then raise exception 'That FAQ no longer exists.' using errcode = 'P0002'; end if;
  insert into public.faq_categories (name, sort)
    select s ->> 'category', coalesce((select max(sort) from public.faq_categories), 0) + 10
    where not exists (select 1 from public.faq_categories where name = s ->> 'category');
  update public.faq set category = s ->> 'category', question = s ->> 'question', answer = s ->> 'answer',
    links = coalesce(s -> 'links', '[]'::jsonb), media = coalesce(s -> 'media', '[]'::jsonb),
    version = old.version + 1, updated_at = now(), updated_by_name = me.name
  where id = old.id returning * into f;
  insert into public.faq_versions (faq_id, version, action, reason, before, after, by_email, by_name)
  values (f.id, f.version, 'restored', r, public.faq_snap(old), public.faq_snap(f) || jsonb_build_object('from_version', v.version), me.email, me.name);
  return f.version;
end $$;

-- Owner only: delete (moves to the Deleted list) and bring back.
create or replace function public.faq_delete(p_id bigint, p_reason text)
returns void language plpgsql security definer set search_path = public as $$
declare me record; f public.faq; old public.faq; r text := public.faq_reason(p_reason);
begin
  if not public.is_owner() then raise exception 'Only the site owner can delete FAQs.' using errcode = '42501'; end if;
  select * into me from public.faq_me();
  select * into old from public.faq where id = p_id and deleted_at is null for update;
  if not found then raise exception 'That FAQ no longer exists.' using errcode = 'P0002'; end if;
  update public.faq set deleted_at = now(), deleted_by_name = me.name, version = old.version + 1, updated_at = now(), updated_by_name = me.name
  where id = p_id returning * into f;
  insert into public.faq_versions (faq_id, version, action, reason, before, after, by_email, by_name)
  values (f.id, f.version, 'deleted', r, public.faq_snap(old), public.faq_snap(f), me.email, me.name);
end $$;

create or replace function public.faq_undelete(p_id bigint, p_reason text)
returns void language plpgsql security definer set search_path = public as $$
declare me record; f public.faq; old public.faq; r text := public.faq_reason(p_reason);
begin
  if not public.is_owner() then raise exception 'Only the site owner can restore deleted FAQs.' using errcode = '42501'; end if;
  select * into me from public.faq_me();
  select * into old from public.faq where id = p_id and deleted_at is not null for update;
  if not found then raise exception 'That FAQ isn''t deleted.' using errcode = 'P0002'; end if;
  update public.faq set deleted_at = null, deleted_by_name = null, version = old.version + 1, updated_at = now(), updated_by_name = me.name
  where id = p_id returning * into f;
  insert into public.faq_versions (faq_id, version, action, reason, before, after, by_email, by_name)
  values (f.id, f.version, 'undeleted', r, public.faq_snap(old), public.faq_snap(f), me.email, me.name);
end $$;

-- The whole FAQ as it stood at a past moment (for the "as of" date picker).
create or replace function public.faq_as_of(p_at timestamptz)
returns table (id bigint, category text, question text, answer text, links jsonb, media jsonb, sort integer, changed_at timestamptz, changed_by text)
language sql stable security definer set search_path = public as $$
  with last as (
    select distinct on (v.faq_id) v.faq_id, v.after, v.at, v.by_name
    from public.faq_versions v
    where v.faq_id is not null and v.at <= p_at and v.after is not null
    order by v.faq_id, v.at desc, v.id desc
  )
  select l.faq_id, l.after ->> 'category', l.after ->> 'question', l.after ->> 'answer',
         coalesce(l.after -> 'links', '[]'::jsonb), coalesce(l.after -> 'media', '[]'::jsonb),
         coalesce((l.after ->> 'sort')::int, 0), l.at, l.by_name
  from last l join public.faq f on f.id = l.faq_id
  where public.faq_can_read()
    and coalesce((l.after ->> 'hidden')::boolean, false) = false
    and coalesce((l.after ->> 'deleted')::boolean, false) = false
    and (f.deleted_at is null or public.is_owner());
$$;

revoke all on function public.faq_snap(public.faq), public.faq_reason(text), public.faq_clean_links(jsonb),
